    /// <summary>Trims a formula so a table cell stays readable.</summary>
    private static string Shorten(string text, int length = 90)
    {
        var single = text.Replace('\n', ' ').Replace('\r', ' ').Trim();
        return single.Length <= length ? single : single[..length] + "...";
    }

