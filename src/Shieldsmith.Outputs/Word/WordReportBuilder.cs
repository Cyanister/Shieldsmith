    private static Table KeyValueTable(IReadOnlyList<(string Key, string Value)> pairs)
    {
        var table = NewTable(2);
        foreach (var (key, value) in pairs)
        {
            table.Append(new TableRow(
                BoldCell(key),
                PlainCell(value)));
        }
        return table;
    }

    private static Table DataTable(IReadOnlyList<string[]> rows)
    {
        var table = NewTable(rows[0].Length);
        for (var i = 0; i < rows.Count; i++)
        {
            var row = new TableRow();
            if (i == 0) row.Append(new TableRowProperties(new TableHeader()));
            // Banded rows: a long attribute table is read a row at a time, and
            // the tint is what stops the eye slipping a line.
            var band = i > 0 && i % 2 == 0 ? WordStyles.BandTint : null;
            foreach (var cellText in rows[i])
                row.Append(i == 0 ? HeaderCell(cellText) : PlainCell(cellText, band));
            table.Append(row);
        }
        return table;
    }

    private static Table NewTable(int columnCount)
    {
        var grid = new TableGrid();
        for (var i = 0; i < columnCount; i++)
            grid.Append(new GridColumn());
        return new Table(
            new TableProperties(
                new TableStyle { Val = WordStyles.TableStyle },
                new TableWidth { Width = "5000", Type = TableWidthUnitValues.Pct },
                new TableLayout { Type = TableLayoutValues.Autofit }),
            grid);
    }

    /// <summary>Cell paragraphs drop the document's after-spacing; inherited
    /// paragraph gaps inside table cells make every row needlessly tall.</summary>
    private static ParagraphProperties CellParagraphProperties() =>
        new(new SpacingBetweenLines { After = "0" });

    private static TableCell HeaderCell(string text) =>
        new(new TableCellProperties(
                new Shading { Val = ShadingPatternValues.Clear, Fill = WordStyles.Accent },
                new TableCellVerticalAlignment { Val = TableVerticalAlignmentValues.Center }),
            new Paragraph(
                CellParagraphProperties(),
                new Run(
                    new RunProperties(new Bold(), new Color { Val = "FFFFFF" }),
                    new Text(text) { Space = SpaceProcessingModeValues.Preserve })));

    private static TableCell BoldCell(string text) =>
        new(new TableCellProperties(
                new Shading { Val = ShadingPatternValues.Clear, Fill = WordStyles.BandTint }),
            new Paragraph(
                CellParagraphProperties(),
                new Run(
                    new RunProperties(new Bold()),
                    new Text(text) { Space = SpaceProcessingModeValues.Preserve })));

    private static TableCell PlainCell(string text, string? shading = null)
    {
        var cell = new TableCell(new Paragraph(
            CellParagraphProperties(),
            new Run(new Text(text) { Space = SpaceProcessingModeValues.Preserve })));
        if (shading is not null)
            cell.PrependChild(new TableCellProperties(
                new Shading { Val = ShadingPatternValues.Clear, Fill = shading }));
        return cell;
    }

    private static void AppendPluginSteps(Body body, IReadOnlyCollection<SdkMessageStepModel> steps)
    {
        if (steps.Count == 0)
        {
            body.Append(Text("No registered steps in this solution."));
            return;
        }

        var rows = new List<string[]>
        {
            new[] { "Message", "Table", "Stage", "Mode", "Rank", "Filtering columns" },
        };
        foreach (var step in steps.OrderBy(s => s.PrimaryEntity).ThenBy(s => s.Rank))
        {
            // The export carries a message GUID, not a name. Where the name
            // could not be recovered this says so rather than leaving a blank
            // cell that reads as "no message".
            rows.Add(new[]
            {
                step.Message.Length > 0 ? step.Message : "not stated in the export",
                step.PrimaryEntity,
                step.Stage,
                step.Mode,
                step.Rank.ToString(),
                step.FilteringAttributes.Count > 0
                    ? string.Join(", ", step.FilteringAttributes)
                    : "all columns",
            });
        }
        body.Append(DataTable(rows));
    }

    private static void AppendImage(MainDocumentPart mainPart, Body body, string pngPath)
    {
        double widthInches, heightInches;
        using (var image = System.Drawing.Image.FromFile(pngPath))
        {
            widthInches = image.Width / (double)image.HorizontalResolution;
            heightInches = image.Height / (double)image.VerticalResolution;
        }

        // Fit to the text column, and cap height so a tall flow chart does not
        // run off the page.
        var scale = Math.Min(1.0, ContentWidthInches / widthInches);
        const double maxHeightInches = 8.2;
        if (heightInches * scale > maxHeightInches)
            scale = maxHeightInches / heightInches;
        var cx = (long)(widthInches * scale * EmuPerInch);
        var cy = (long)(heightInches * scale * EmuPerInch);

        var imagePart = mainPart.AddImagePart(ImagePartType.Png);
        using (var stream = File.OpenRead(pngPath))
            imagePart.FeedData(stream);
        var relationshipId = mainPart.GetIdOfPart(imagePart);

        // Drawing ids must be unique within the document; the part count gives a
        // fresh number per image without a static counter shared across writes.
        var drawingId = (uint)mainPart.ImageParts.Count();

        var drawing = new Drawing(
            new DW.Inline(
                new DW.Extent { Cx = cx, Cy = cy },
                new DW.DocProperties { Id = drawingId, Name = $"Diagram {drawingId}" },
                new A.Graphic(
                    new A.GraphicData(
                        new PIC.Picture(
                            new PIC.NonVisualPictureProperties(
                                new PIC.NonVisualDrawingProperties { Id = drawingId, Name = Path.GetFileName(pngPath) },
                                new PIC.NonVisualPictureDrawingProperties()),
                            new PIC.BlipFill(
                                new A.Blip { Embed = relationshipId },
                                new A.Stretch(new A.FillRectangle())),
                            new PIC.ShapeProperties(
                                new A.Transform2D(
                                    new A.Offset { X = 0L, Y = 0L },
                                    new A.Extents { Cx = cx, Cy = cy }),
                                new A.PresetGeometry(new A.AdjustValueList()) { Preset = A.ShapeTypeValues.Rectangle })))
                    { Uri = "http://schemas.openxmlformats.org/drawingml/2006/picture" }))
            { DistanceFromTop = 0U, DistanceFromBottom = 0U, DistanceFromLeft = 0U, DistanceFromRight = 0U });

        body.Append(new Paragraph(new Run(drawing)));
    }
